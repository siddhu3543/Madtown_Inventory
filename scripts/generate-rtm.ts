/** Builds docs/RTM.md + docs/rtm.csv from requirements.json, rtm-map.ts and the latest test reports. */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { MAP } from "./rtm-map";

type R = { id: string; cells: string[] };
const reqs: R[] = JSON.parse(readFileSync("docs/source/requirements.json", "utf8"));
type T = { title: string; status: "passed" | "failed" | "skipped"; src: string };
const tests: T[] = [];
if (existsSync("test-results/vitest.json")) {
  const v = JSON.parse(readFileSync("test-results/vitest.json", "utf8"));
  for (const f of v.testResults) for (const a of f.assertionResults) tests.push({ title: a.fullName, status: a.status, src: f.name.split("madtown-inventory/")[1] });
}
if (existsSync("test-results/e2e.json")) {
  const e = JSON.parse(readFileSync("test-results/e2e.json", "utf8"));
  const walk = (s: { specs?: { title: string; file: string; tests: { projectName: string; results: { status: string }[] }[] }[]; suites?: unknown[] }, prefix = "") => {
    for (const sp of s.specs ?? [])
      for (const t of sp.tests)
        tests.push({ title: `${prefix}${sp.title} [${t.projectName}]`, status: t.results.at(-1)?.status === "passed" ? "passed" : "failed", src: `tests/e2e/${sp.file}` });
    for (const c of (s.suites ?? []) as (typeof s & { title: string })[]) walk(c, prefix + (c.title && !c.title.endsWith(".ts") ? c.title + " > " : ""));
  };
  for (const s of e.suites) walk(s);
}
const unmatched: string[] = [];
const find = (needle: string) => {
  const h = tests.filter((t) => t.title.includes(needle));
  if (!h.length) unmatched.push(needle);
  return h;
};

const rows = reqs.map((r) => {
  const id = r.id;
  const isAC = id.startsWith("AC-"),
    isOQ = id.startsWith("OQ-");
  const text = isAC ? r.cells[1] : r.cells[0];
  const phase = id.startsWith("FR-")
    ? r.cells[2]
    : id.startsWith("NFR")
      ? r.cells[3]
      : isAC
        ? r.cells[2]
        : id.startsWith("NTF")
          ? r.cells[4]
          : id.startsWith("SCR")
            ? r.cells[2]
            : "";
  const priority = id.startsWith("FR-") ? r.cells[1] : id.startsWith("NFR") ? r.cells[2] : "";
  if (isOQ) return { id, text, phase, priority, impl: "docs/OPEN_QUESTIONS.md (configurable default)", tests: "", status: "OPEN — needs product-owner answer", note: "" };
  const m = MAP[id] ?? (isAC ? { impl: "see module FRs", tests: [id] } : undefined);
  if (!m) return { id, text, phase, priority, impl: "", tests: "", status: "NOT MAPPED", note: "" };
  const hits = (m.tests ?? []).flatMap(find);
  const passed = hits.filter((h) => h.status === "passed"),
    failed = hits.filter((h) => h.status !== "passed");
  let status: string;
  if (failed.length) status = "FAILING";
  else if (m.kind === "road") status = "Roadmap (Phase 3) — not built";
  else if (m.kind === "proc") status = "Process / Madtown action";
  else if (m.kind === "doc") status = "Delivered (documentation)";
  else if (m.kind === "ext") status = passed.length ? "Verified locally; needs Madtown account to verify live" : "Built behind adapter; needs Madtown account";
  else if (passed.length) status = "Verified (automated)";
  else status = "Implemented — no automated test";
  if (phase === "3" && m.kind !== "road" && status.startsWith("Verified")) status += " (Phase 3 item built early)";
  const testList = [...new Set(passed.map((h) => `${h.src}: ${h.title.slice(0, 90)}`))].slice(0, 3).join("<br>");
  return { id, text, phase, priority, impl: m.impl, tests: testList + (passed.length > 3 ? `<br>+${passed.length - 3} more` : ""), status, note: m.note ?? "" };
});
const esc = (s: string) => (s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");
const counts: Record<string, number> = {};
for (const r of rows) counts[r.status] = (counts[r.status] ?? 0) + 1;
const groups: [string, (id: string) => boolean][] = [
  ["Goals", (i) => i.startsWith("G-")],
  ["Functional requirements", (i) => i.startsWith("FR-")],
  ["Non-functional", (i) => i.startsWith("NFR")],
  ["Notifications", (i) => i.startsWith("NTF")],
  ["Screens", (i) => i.startsWith("SCR")],
  ["Migration rules", (i) => i.startsWith("MIG")],
  ["Acceptance criteria", (i) => i.startsWith("AC-")],
  ["Risks", (i) => i.startsWith("R-")],
  ["Open questions", (i) => i.startsWith("OQ-")],
];
let md = `# Requirements traceability matrix\n\nGenerated by \`npm run rtm\` from docs/source/requirements.json (all ${rows.length} identifiers parsed from Draft v0.1), scripts/rtm-map.ts and the latest test reports (${tests.length} automated tests: ${tests.filter((t) => t.status === "passed").length} passed, ${tests.filter((t) => t.status !== "passed").length} not passed). A requirement is only marked *Verified* when a mapped automated test passed in that run (A6).\n\n`;
md +=
  "**Important:** acceptance tests ran on the SYNTHETIC sheet reconstruction and an in-workspace staging (PostgreSQL 16 + production Next.js build). They must be re-run on the real sheet export and the Madtown Supabase/Vercel staging before sign-off (section 13: tester Naveen or Anand).\n\n## Status summary\n\n| Status | Count |\n|---|---|\n";
for (const [k, v] of Object.entries(counts).sort((a, b) => b[1] - a[1])) md += `| ${k} | ${v} |\n`;
for (const [g, f] of groups) {
  md += `\n## ${g}\n\n| ID | Requirement | Pri | Ph | Implementation | Evidence (passing tests) | Status | Note |\n|---|---|---|---|---|---|---|---|\n`;
  for (const r of rows.filter((x) => f(x.id)))
    md += `| ${r.id} | ${esc(r.text).slice(0, 220)} | ${r.priority} | ${r.phase} | ${esc(r.impl)} | ${r.tests} | **${r.status}** | ${esc(r.note)} |\n`;
}
writeFileSync("docs/RTM.md", md);
writeFileSync(
  "docs/rtm.csv",
  [
    "id,priority,phase,status,implementation,note",
    ...rows.map((r) => [r.id, r.priority, r.phase, r.status, r.impl, r.note].map((x) => `"${String(x ?? "").replace(/"/g, '""')}"`).join(",")),
  ].join("\n"),
);
console.log(counts);
if (unmatched.length) console.log("UNMATCHED test references:", [...new Set(unmatched)]);
